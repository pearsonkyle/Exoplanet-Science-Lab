// Saving figures and tables. In a claude.ai artifact, files go through the
// platform's downloads capability; everywhere else a normal browser download.

let downloadsCap;   // undefined = not asked yet, null = unavailable
async function capability() {
  if (downloadsCap !== undefined) return downloadsCap;
  try { downloadsCap = window.claude && window.claude.use ? await window.claude.use('downloads') : null; } catch { downloadsCap = null; }
  return downloadsCap;
}

/** Returns 'saved', 'declined' or throws. */
export async function saveFile(filename, data) {
  const cap = await capability();
  if (cap) {
    // the capability only accepts a fixed list of extensions; LaTeX goes out as .txt there
    const name = filename.replace(/\.(tex|yaml)$/, '.$1.txt');
    try { await cap.save({ filename: name, data }); return 'saved'; }
    catch (err) { if (err && err.code === 'declined') return 'declined'; if (!err || !/unavailable|not_granted|capability/.test(err.code || '')) throw new Error(err && err.message ? err.message : 'save failed'); }
  }
  const blob = data instanceof Blob ? data : new Blob([data]);
  const url = URL.createObjectURL(blob), a = document.createElement('a');
  a.href = url; a.download = filename; document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
  return 'saved';
}

export const canvasToPNG = (canvas) => new Promise((res, rej) => canvas.toBlob((b) => (b ? res(b) : rej(new Error('could not encode PNG'))), 'image/png'));

async function deflate(bytes) {
  if (typeof CompressionStream === 'undefined') return null;
  const cs = new CompressionStream('deflate');           // zlib container, which is what PDF's FlateDecode expects
  const out = new Response(new Blob([bytes]).stream().pipeThrough(cs));
  return new Uint8Array(await out.arrayBuffer());
}

/** One-page PDF holding the canvas as a lossless image at its full resolution. */
export async function canvasToPDF(canvas) {
  const w = canvas.width, h = canvas.height, rgba = canvas.getContext('2d').getImageData(0, 0, w, h).data;
  const rgb = new Uint8Array(w * h * 3);
  for (let i = 0, j = 0; i < rgba.length; i += 4) { rgb[j++] = rgba[i]; rgb[j++] = rgba[i + 1]; rgb[j++] = rgba[i + 2]; }
  const z = await deflate(rgb), img = z || rgb;
  const pw = ((canvas._cssW || w) * 0.75).toFixed(2), ph = ((canvas._cssH || h) * 0.75).toFixed(2);   // CSS px -> points
  const enc = new TextEncoder(), parts = [], offs = []; let len = 0;
  const push = (x) => { const b = typeof x === 'string' ? enc.encode(x) : x; parts.push(b); len += b.length; };
  const obj = (n, body) => { offs[n] = len; push(`${n} 0 obj\n`); body(); push('\nendobj\n'); };
  push('%PDF-1.4\n%\xE2\xE3\xCF\xD3\n');
  obj(1, () => push('<< /Type /Catalog /Pages 2 0 R >>'));
  obj(2, () => push('<< /Type /Pages /Kids [3 0 R] /Count 1 >>'));
  obj(3, () => push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pw} ${ph}] /Resources << /XObject << /Im0 4 0 R >> >> /Contents 5 0 R >>`));
  obj(4, () => { push(`<< /Type /XObject /Subtype /Image /Width ${w} /Height ${h} /ColorSpace /DeviceRGB /BitsPerComponent 8 ${z ? '/Filter /FlateDecode ' : ''}/Length ${img.length} >>\nstream\n`); push(img); push('\nendstream'); });
  const content = `q ${pw} 0 0 ${ph} 0 0 cm /Im0 Do Q`;
  obj(5, () => push(`<< /Length ${content.length} >>\nstream\n${content}\nendstream`));
  const xref = len;
  push(`xref\n0 6\n0000000000 65535 f \n` + [1, 2, 3, 4, 5].map((n) => String(offs[n]).padStart(10, '0') + ' 00000 n \n').join(''));
  push(`trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`);
  return new Blob(parts, { type: 'application/pdf' });
}

const texNum = (s, dg) => {
  if (s.plus === undefined) return `$${s.med.toFixed(dg)}$`;
  const p = s.plus.toFixed(dg), m = s.minus.toFixed(dg);
  return p === m ? `$${s.med.toFixed(dg)} \\pm ${p}$` : `$${s.med.toFixed(dg)}^{+${p}}_{-${m}}$`;
};

/** rows: [{ tex, unit, s: {med, plus, minus} | {med}, dg, note }] */
export function latexTable(rows, caption, footer) {
  const body = rows.map((r) => (r.section ? `\\hline\n\\multicolumn{3}{l}{\\textit{${r.section}}} \\\\` : `${r.tex} & ${r.unit || ''} & ${texNum(r.s, r.dg)} \\\\`)).join('\n');
  return `% Generated by Exoplanet Science Lab\n\\begin{table}\n\\centering\n\\caption{${caption}}\n\\begin{tabular}{llc}\n\\hline\\hline\nParameter & Unit & Value \\\\\n${body}\n\\hline\n\\end{tabular}\n${footer ? `\\par\\smallskip\n{\\footnotesize ${footer}}\n` : ''}\\end{table}\n`;
}
