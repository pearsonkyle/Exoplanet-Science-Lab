// The Methods document in its three generated forms, from one source (src/methods/content.js):
//
//   node tools/build_methods_md.mjs            write docs/METHODS.md, docs/references.bib and src/methods/results.generated.js
//   node tools/build_methods_md.mjs --check    exit 1 when any of them is not what the sources give now (nothing is written)
//
// src/methods/results.generated.js is the extract of public/examples/results/*.json that the reproducibility table
// quotes (only the values the table shows), so the page needs no fetch and the Markdown and the page print the same
// numbers. Rerun this after tools/build_example_results.py, after editing content.js or src/validation/topics.js,
// and after adding a reference to src/validation/refs.js. The output is a pure function of the sources: no clock.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as CONTENT from '../src/methods/content.js';
import { TOPICS } from '../src/validation/topics.js';
import { REFS } from '../src/validation/refs.js';
import { methodsParagraph, allBibtex } from '../src/core/methodsText.js';

const P = (p) => fileURLToPath(new URL('../' + p, import.meta.url)), check = process.argv.includes('--check');
const pkg = JSON.parse(readFileSync(P('package.json'), 'utf8'));

// CITATION.cff must name the version of package.json
const cff = readFileSync(P('CITATION.cff'), 'utf8');
if (!cff.includes(`version: "${pkg.version}"`)) throw new Error(`CITATION.cff does not carry version ${pkg.version} of package.json`);

// ---- 1. the extract of the stored example results
const dir = P('public/examples/results/'), sessions = Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => [f.replace('.json', ''), JSON.parse(readFileSync(dir + f, 'utf8'))]));
const examples = {}; let newest = '';
for (const ex of CONTENT.EXAMPLES) {
  if (!ex.id) continue;
  const s = sessions[ex.id]; if (!s || !s.result) throw new Error(`example ${ex.id}: no stored result in public/examples/results/`);
  const r = s.result, values = {}, par = Object.fromEntries(r.parameters.map((p) => [p.key, p]));
  for (const c of ex.compare) {
    if (!c.get) continue;
    const [kind, key] = c.get; let v;
    if (kind === 'parameters') v = par[key] && { median: par[key].median, plus: par[key].plus, minus: par[key].minus };
    else if (kind === 'derived') v = r.derived && r.derived[key];
    else if (kind === 'calc' && key === 'depthPpm') v = { median: Math.round(par.fpfs.median * par.rprs.median ** 2 * 1e6), plus: 0, minus: 0 };
    if (!v || !Number.isFinite(v.median)) throw new Error(`example ${ex.id}: ${kind}.${key} is not in the stored result`);
    values[`${kind}.${key}`] = { median: v.median, plus: v.plus, minus: v.minus };
  }
  examples[ex.id] = { created: s.created, version: s.software.version, free: s.fit.free.length, ncalls: r.ncalls, logZ: r.logZ, logZerr: r.logZerr, converged: !!r.converged, warnings: (r.warnings || []).length, n_data: r.n_data, values };
  if (String(s.created) > newest) newest = String(s.created);
}
const RESULTS = { extracted: `from files dated up to ${newest.slice(0, 10)}`, examples };
const resultsJs = `// Generated by tools/build_methods_md.mjs from public/examples/results/*.json. Do not edit.\nexport const RESULTS = ${JSON.stringify(RESULTS, null, 1)};\n`;

// ---- 2. Markdown and BibTeX
const { buildMarkdown } = await import('../src/methods/render.js');
const sample = methodsParagraph(sessions['hd80606-joint']);
const md = buildMarkdown({ ...CONTENT, TOPICS, REFS, RESULTS, sample: { name: 'hd80606-joint.json', ...sample } });
const bib = `% References of Exoplanet Science Lab ${pkg.version}: the software itself (key: esl) and every entry of src/validation/refs.js.\n% Generated by tools/build_methods_md.mjs; do not edit. UTF-8. Entries were checked against Crossref, arXiv or ASCL on 2026-11-15;\n% what could not be checked is noted in refs.js and on the Methods page.\n\n` + allBibtex({ version: pkg.version, year: 2026 });

// ---- 3. every key cited in the text exists and every methods-only reference is cited somewhere
const text = JSON.stringify(CONTENT), cited = new Set([...text.matchAll(/@([A-Za-z0-9]+)/g)].map((m) => m[1]).filter((k) => REFS[k]));
for (const s of CONTENT.SECTIONS) for (const k of s.refs || []) { if (!REFS[k]) throw new Error(`${s.id}: unknown reference ${k}`); cited.add(k); }
for (const ex of CONTENT.EXAMPLES) for (const k of ex.cite) { if (!REFS[k]) throw new Error(`example ${ex.title}: unknown reference ${k}`); cited.add(k); }
for (const d of CONTENT.DATA_TERMS) for (const k of d[3]) cited.add(k);
for (const k of ['skilling2006', 'neal2003', 'husser2013', 'danby1987', 'luger2019', 'wisdom1991', 'rein2015whfast', 'rein2015ias15']) cited.add(k);   // methodsText.js
const orphans = Object.keys(REFS).filter((k) => REFS[k].methods && !cited.has(k));
if (orphans.length) throw new Error('references marked methods: true but not cited by the Methods document: ' + orphans.join(', '));

const files = [['src/methods/results.generated.js', resultsJs], ['docs/METHODS.md', md], ['docs/references.bib', bib]];
let stale = 0;
for (const [f, body] of files) {
  let old = null; try { old = readFileSync(P(f), 'utf8'); } catch { /* new file */ }
  if (check) { if (old !== body) { console.log(`STALE ${f}`); stale++; } else console.log(`ok   ${f}`); }
  else { mkdirSync(P(f).replace(/[^/]+$/, ''), { recursive: true }); writeFileSync(P(f), body); console.log(`${old === body ? 'unchanged' : 'wrote    '} ${f}   ${body.length} bytes`); }
}
console.log(`${CONTENT.SECTIONS.length} sections, ${Object.keys(examples).length} stored examples, ${Object.keys(REFS).length} references (${cited.size} cited by the Methods document), ${md.split(/\s+/).length} words`);
process.exit(stale ? 1 : 0);
