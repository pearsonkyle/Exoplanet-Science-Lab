"""Build the Python labs: python/labs/src/labNN_*.py (cells marked "# %%" and "# %% [markdown]") become executed
notebooks (python/labs/labNN_*.ipynb, with their outputs and figures) and documentation pages (docs/labs/labNN_*.md,
figures in docs/public/labs/). Executing needs the package and a kernel:

    .venv-py/bin/pip install nbformat nbclient ipykernel matplotlib && .venv-py/bin/python -m ipykernel install --user --name esl-labs
    .venv-py/bin/python tools/docs/build_labs.py            # all labs
    .venv-py/bin/python tools/docs/build_labs.py lab03      # one

The labs download their data from the published site (ESL_DATA overrides the address), so a notebook runs anywhere
after `pip install`. The outputs are committed: the docs build does not run them.
"""
import base64
import pathlib
import re
import sys
import time

import nbformat
from nbclient import NotebookClient

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC, NB, MD, IMG = ROOT / "python/labs/src", ROOT / "python/labs", ROOT / "docs/labs", ROOT / "docs/public/labs"
REPO = "https://github.com/pearsonkyle/Exoplanet-Science-Lab"


def cells_of(text):
    """Split a percent-format script into (kind, source) cells."""
    out, kind, buf = [], None, []
    for line in text.splitlines():
        m = re.match(r"^# %%( \[markdown\])?\s*$", line)
        if m:
            if kind is not None:
                out.append((kind, "\n".join(buf).strip("\n")))
            kind, buf = ("markdown" if m.group(1) else "code"), []
            continue
        if kind == "markdown":
            buf.append(re.sub(r"^# ?", "", line))
        elif kind == "code":
            buf.append(line)
    if kind is not None:
        out.append((kind, "\n".join(buf).strip("\n")))
    return [c for c in out if c[1]]


def build(src):
    stem = src.stem
    nb = nbformat.v4.new_notebook()
    nb.metadata["kernelspec"] = {"name": "esl-labs", "display_name": "Python (ESL labs)", "language": "python"}
    for kind, text in cells_of(src.read_text()):
        nb.cells.append(nbformat.v4.new_markdown_cell(text) if kind == "markdown" else nbformat.v4.new_code_cell(text))
    t0 = time.time()
    NotebookClient(nb, timeout=1800, kernel_name="esl-labs", resources={"metadata": {"path": str(NB)}}).execute()
    secs = time.time() - t0
    NB.mkdir(parents=True, exist_ok=True)
    nbformat.write(nb, NB / f"{stem}.ipynb")
    # the documentation page: text, code, its printed output and its figures
    IMG.mkdir(parents=True, exist_ok=True)
    md, nfig = [], 0
    title = next((c.source.splitlines()[0].lstrip("# ").strip() for c in nb.cells if c.cell_type == "markdown"), stem)
    for c in nb.cells:
        if c.cell_type == "markdown":
            md.append(c.source)
            if c is nb.cells[0]:
                md.append(f"\n<div class=\"labbar\"><a href=\"{REPO}/blob/main/python/labs/{stem}.ipynb\">Notebook</a> · "
                          f"<a href=\"https://colab.research.google.com/github/pearsonkyle/Exoplanet-Science-Lab/blob/main/python/labs/{stem}.ipynb\">Open in Colab</a> · "
                          f"runs in about {max(1, round(secs))} s</div>")
            continue
        md.append("```python\n" + c.source + "\n```")
        for o in c.get("outputs", []):
            if o.output_type == "stream" and o.text.strip():
                md.append("```text\n" + o.text.rstrip() + "\n```")
            elif o.output_type in ("execute_result", "display_data"):
                data = o.get("data", {})
                if "image/png" in data:
                    nfig += 1
                    name = f"{stem}_{nfig}.png"
                    (IMG / name).write_bytes(base64.b64decode(data["image/png"]))
                    md.append(f"![{title}, figure {nfig}](/labs/{name})")
                elif "text/plain" in data and not data["text/plain"].startswith("<Figure"):
                    md.append("```text\n" + data["text/plain"].rstrip() + "\n```")
            elif o.output_type == "error":
                raise RuntimeError(f"{stem}: {o.ename}: {o.evalue}")
    MD.mkdir(parents=True, exist_ok=True)
    (MD / f"{stem}.md").write_text("<!-- generated by tools/docs/build_labs.py from python/labs/src: edit the source, not this page -->\n\n" + "\n\n".join(md) + "\n")
    print(f"{stem}: {len(nb.cells)} cells, {nfig} figures, {secs:.0f} s")


if __name__ == "__main__":
    pick = sys.argv[1:]
    for src in sorted(SRC.glob("lab*.py")):
        if not pick or any(src.stem.startswith(p) for p in pick):
            build(src)
