"""Optical constants of aerosol materials for src/core/optical.js, from the compilation of Kitzmann & Heng (2018).

    .venv/bin/python -I tools/opacity/build_optical.py data-src/tholin/Titan_tholin.dat

Reads a three-column file (wavelength [micron], n, k; three header lines) and writes n and k at 160 wavelengths spaced
evenly in log from 0.2 to 50 micron (the compilation's 10000 points are themselves an interpolation of the 90-odd
measured ones). The tholin file is Khare et al. (1984, Icarus 60, 127): a laboratory analogue of Titan's haze made
by discharge in N2 with 10% CH4.
"""
import sys, os
import numpy as np

src = sys.argv[1]
d = np.loadtxt(src, skiprows=3)
wl = 0.2 * (50 / 0.2) ** (np.arange(160) / 159)
n = np.interp(np.log(wl), np.log(d[:, 0]), d[:, 1])
k = np.exp(np.interp(np.log(wl), np.log(d[:, 0]), np.log(d[:, 2])))
fmt = lambda a, p: '[' + ', '.join(f'{v:.{p}g}' for v in a) + ']'
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'core', 'optical.js')
open(out, 'w').write(f'''// Optical constants (refractive index n + i k) of aerosol materials, for src/core/mie.js. Generated by
// tools/opacity/build_optical.py; do not edit.
//   tholin   Khare et al. (1984, Icarus 60, 127): a laboratory analogue of Titan's haze (discharge in N2 with 10% CH4),
//            as compiled by Kitzmann & Heng (2018, MNRAS 475, 94). 160 wavelengths, 0.2 to 50 micron.
export const OPTICAL = {{
  tholin: {{ name: 'tholin', label: 'Titan tholin (Khare et al. 1984)', wl: {fmt(wl, 5)},
    n: {fmt(n, 5)},
    k: {fmt(k, 4)} }},
}};
''')
print('wrote', out, 'n(0.55) =', np.interp(0.55, wl, n), 'k at 0.4, 0.55, 1.0, 3.0, 4.6:', [float(np.interp(x, wl, k)) for x in (0.4, 0.55, 1.0, 3.0, 4.6)])
