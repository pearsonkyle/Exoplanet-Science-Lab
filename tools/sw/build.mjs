// Writes dist/sw.js: the service worker (tools/sw/template.js) with the list of every file in dist/ and its hash,
// so the offline copy always matches the build. Run after the build; vite.config.js runs it after `vite build`, and
// tools/docs/assemble.mjs again once the docs are in dist/docs.
//
//   node tools/sw/build.mjs [dist]       prints the version, the file counts and the sizes
//
// SHELL is installed before the worker takes over (every page must open offline); DATA is saved in the background
// afterwards (large catalogue snapshots, examples, sample FITS, the docs).
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const SKIP = [/^sw\.js$/, /^\.nojekyll$/, /\.map$/, /(^|\/)\.DS_Store$/];
// large or rarely opened at start: saved in the background. Everything else is the shell.
const DATA = [/^docs\//, /^catalog\/shard-/, /^catalog-table\//, /^catalog-eu\//, /^esl-catalog\/catalog\.json$/, /^examples\//, /^photometry\//, /^opacity\//, /^chem\//, /^stellar\//];

function walk(dir, root, out = []) {
  for (const name of readdirSync(dir)) {
    const f = join(dir, name), st = statSync(f);
    if (st.isDirectory()) walk(f, root, out);
    else out.push({ path: relative(root, f).split(sep).join('/'), size: st.size, file: f });
  }
  return out;
}

export function buildServiceWorker(dist = 'dist', { quiet = false } = {}) {
  if (!existsSync(join(dist, 'index.html'))) throw new Error(`${dist}/index.html not found: build first`);
  const files = walk(dist, dist).filter((f) => !SKIP.some((r) => r.test(f.path))).sort((a, b) => (a.path < b.path ? -1 : 1));
  const shell = [], data = []; let shellBytes = 0, dataBytes = 0;
  const all = createHash('sha256');
  for (const f of files) {
    const h = createHash('sha256').update(readFileSync(f.file)).digest('hex').slice(0, 16);
    all.update(f.path + ' ' + h + '\n');
    // a folder's index.html is cached under the folder's own address too (see matchPage in the template)
    if (DATA.some((r) => r.test(f.path))) { data.push([f.path, h]); dataBytes += f.size; } else { shell.push([f.path, h]); shellBytes += f.size; }
  }
  const version = all.digest('hex').slice(0, 12);
  const tpl = readFileSync(fileURLToPath(new URL('./template.js', import.meta.url)), 'utf8');
  const head = `// generated by tools/sw/build.mjs: ${files.length} files, ${(shellBytes / 1e6).toFixed(1)} MB shell + ${(dataBytes / 1e6).toFixed(1)} MB background\n`
    + `const VERSION = ${JSON.stringify(version)};\nconst BYTES = ${shellBytes + dataBytes};\n`
    + `const SHELL = ${JSON.stringify(shell)};\nconst DATA = ${JSON.stringify(data)};\n\n`;
  writeFileSync(join(dist, 'sw.js'), head + tpl);
  const r = { version, files: files.length, shell: shell.length, data: data.length, shellBytes, dataBytes };
  if (!quiet) console.log(`sw.js ${version}: ${r.shell} shell files (${(shellBytes / 1e6).toFixed(1)} MB) + ${r.data} saved in the background (${(dataBytes / 1e6).toFixed(1)} MB) = ${((shellBytes + dataBytes) / 1e6).toFixed(1)} MB`);
  return r;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) buildServiceWorker(process.argv[2] || 'dist');
